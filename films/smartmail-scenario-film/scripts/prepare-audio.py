#!/usr/bin/env python3
"""Compose an original 120 BPM score and prepare documented physical SFX."""
import json
from pathlib import Path
import subprocess
import numpy as np
from scipy.signal import butter,sosfilt
from scipy.io.wavfile import write

ROOT=Path(__file__).resolve().parents[1]
LIB=Path('/workspace/video-shotcraft/assets/audio/sfx')
OUT=ROOT/'public/audio';OUT.mkdir(parents=True,exist_ok=True)
SR=48000;DURATION=84;N=SR*DURATION
rng=np.random.default_rng(7319)
mix=np.zeros((N,2),dtype=np.float64)
def add(signal,start,pan=0):
    a=round(start*SR);b=min(N,a+len(signal))
    if a<0 or a>=N:return
    x=signal[:b-a]
    if x.ndim==1:x=np.stack((x*np.sqrt((1-pan)/2),x*np.sqrt((1+pan)/2)),axis=1)
    mix[a:b]+=x
def low(x,hz):return sosfilt(butter(2,hz,fs=SR,output='sos'),x)
def high(x,hz):return sosfilt(butter(2,hz,fs=SR,btype='high',output='sos'),x)
def kick():
    t=np.arange(round(.42*SR))/SR
    phase=2*np.pi*(49*t+88*.016*(1-np.exp(-t/.016)))
    return .2*np.sin(phase)*np.exp(-t*14)+.008*high(rng.normal(size=len(t)),4500)*np.exp(-t*190)
def hat(velocity=1):
    t=np.arange(round(.13*SR))/SR
    return .016*velocity*high(rng.normal(size=len(t)),7200)*np.exp(-t*52)
def snare():
    t=np.arange(round(.23*SR))/SR
    return .036*high(low(rng.normal(size=len(t)),6500),1500)*np.exp(-t*24)+.025*np.sin(2*np.pi*176*t)*np.exp(-t*35)
def bass(hz,length=.31):
    t=np.arange(round(length*SR))/SR
    env=np.minimum(t/.008,1)*np.minimum((length-t)/.07,1)
    return .063*(np.sin(2*np.pi*hz*t)+.21*np.sin(2*np.pi*hz*2*t))*env
roots=[73.4162,58.2705,87.3071,65.4064]
for beat in range(168):
    s=beat*.5
    if 2<=s<80:add(kick(),s)
    if 5<=s<80 and beat%2==1:add(snare(),s,.05)
    if 5<=s<80:
        add(hat(1 if beat%2==0 else .8),s,-.28)
        add(hat(.55),s+.25,.3)
    if 5<=s<80:
        root=roots[(beat//8)%4]
        add(bass(root/2),s+.04)
        if beat%4 in (1,3):add(bass(root/2,.18),s+.34)
for bar in range(21):
    s=bar*4
    length=min(4.7,DURATION-s)
    if length<=0:continue
    t=np.arange(round(length*SR))/SR
    root=roots[bar%4]*2
    semitones=[0,3 if bar%4==0 else 4,7,14]
    env=np.minimum(t/.75,1)*np.minimum((length-t)/1.2,1)
    pad=np.zeros((len(t),2))
    for j,semi in enumerate(semitones):
        hz=root*2**(semi/12)
        for c,detune in enumerate([.9992,1.0008]):
            pad[:,c]+=.019*np.sin(2*np.pi*hz*detune*t+j*.4)*env
    add(pad,s)
    if s>=20:
        for j in range(8):
            ts=np.arange(round(.78*SR))/SR
            hz=root*2**(semitones[j%4]/12)*2
            note=.008*(np.sin(2*np.pi*hz*ts)+.2*np.sin(2*np.pi*hz*2*ts))*np.exp(-ts*5)
            add(note,s+j*.5+.25,(-.25 if j%2 else .25))
fade=np.minimum(np.arange(N)/(SR*1.0),1)*np.minimum((N-np.arange(N))/(SR*1.5),1)
mix*=fade[:,None]
mix=np.tanh(mix*1.35)*.72
write(OUT/'original-score.wav',SR,np.int16(np.clip(mix,-1,1)*32767))

assets={'paper-slide':'paper','paper-page-turn':'paper','switch-light':'ui','switch-click-quick':'ui','marker-pen-line':'text','impact-deep-whoosh':'impact','shimmer-sparkle-sweep':'light','typewriter-hit-soft':'text','typewriter-hit-single':'text'}
records={}
for name,category in assets.items():
    source=LIB/category/(name+'.mp3')
    raw=subprocess.check_output(['ffmpeg','-v','error','-i',str(source),'-f','f32le','-ac','1','-ar',str(SR),'-'])
    x=np.frombuffer(raw,dtype='<f4').copy()
    peak=np.argmax(np.abs(x))
    # Retain up to 60 ms of the source's leading attack, then normalize. This
    # keeps paper/pen texture while giving every cue a measured attack time.
    trim=max(0,int(peak)-round(SR*.06))
    prepared=x[trim:]
    prepared*=.68/max(float(np.max(np.abs(prepared))),1e-5)
    write(OUT/(name+'.wav'),SR,np.int16(np.clip(prepared,-1,1)*32767))
    records[name]={'source':str(source.relative_to(LIB.parent)), 'sourcePeakSamples':int(peak),'trimSamples':trim,'peakFrames':float((peak-trim)/SR*30),'duration':len(prepared)/SR,'preparedPeakDb':float(20*np.log10(np.max(np.abs(prepared))))}
# A restrained original noise riser leads into the finale; no library asset
# with uncertain provenance is used.
t=np.arange(SR)/SR
riser=high(low(rng.normal(size=SR),5000),700)*(t**2)*.034
riser*=np.minimum((1-t)/.035,1)
riser*=.34/max(float(np.max(np.abs(riser))),1e-5)
write(OUT/'original-riser.wav',SR,np.int16(riser*32767))
records['original-riser']={'source':'original composition','peakFrames':float(np.argmax(np.abs(riser))/SR*30),'duration':1,'preparedPeakDb':float(20*np.log10(np.max(np.abs(riser))))}
(OUT/'analysis.json').write_text(json.dumps(records,indent=2))
report={'bpm':120,'beatZeroSeconds':0,'beatFrames':15,'durationSeconds':84,'seed':7319,'sourcePeakDb':float(20*np.log10(np.max(np.abs(mix)))),'music':'Original instrumental composition, generated by this reproducible script. No sampled music.'}
(ROOT/'analysis/music.json').write_text(json.dumps(report,indent=2))
print(json.dumps(report))
